"""Build the ngrok traffic policy and command for the one-tunnel setup (see docs/NGROK_REMOTE.md).

The policy runs at ngrok, before a request reaches this machine:
  * POST /webhook is let through untouched (GitHub cannot sign in; the HMAC signature protects it).
  * every other path first needs a sign-in with Google or GitHub, and only the listed e-mail addresses get through.
The dashboard's own log-in is a second lock behind that. Syntax checked against ngrok's current documentation
(agent config, Traffic Policy: oauth and deny actions, req.url.path). Nothing here talks to ngrok."""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Mapping

PROVIDERS = ("google", "github")
_EMAIL = re.compile(r"^[A-Za-z0-9._%+\-]{1,64}@[A-Za-z0-9\-]+(\.[A-Za-z0-9\-]+)*\.[A-Za-z]{2,}$")
_HOST = re.compile(r"^[a-z0-9]([a-z0-9\-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9\-]*[a-z0-9])?)+$")


def parse_emails(text: str) -> list[str]:
    """'a@x.com, b@y.org' -> ['a@x.com', 'b@y.org']. Anything that is not a plain address is refused, so a typo
    or a hostile value can never become part of the policy expression."""
    emails = [e.strip().lower() for e in re.split(r"[,\s;]+", text or "") if e.strip()]
    for e in emails:
        if not _EMAIL.match(e):
            raise ValueError(f"'{e}' is not a plain e-mail address")
    return list(dict.fromkeys(emails))


def parse_url(text: str) -> str:
    """'https://name.ngrok-free.app/' or 'name.ngrok-free.app' -> 'https://name.ngrok-free.app'. '' stays ''."""
    t = (text or "").strip()
    if not t:
        return ""
    host = re.sub(r"^https?://", "", t, flags=re.I).rstrip("/").lower()
    if "/" in host or not _HOST.match(host):
        raise ValueError(f"'{text}' is not a host name such as name.ngrok-free.app")
    return "https://" + host


def build_policy(emails: list[str], provider: str = "google") -> str:
    if provider not in PROVIDERS:
        raise ValueError(f"provider must be one of {', '.join(PROVIDERS)}")
    if not emails:
        raise ValueError("at least one allowed e-mail address is needed")
    for e in emails:
        if not _EMAIL.match(e):
            raise ValueError(f"'{e}' is not a plain e-mail address")
    listed = ", ".join(f"'{e}'" for e in emails)
    return f"""# Generated by scripts/start_tunnel.py from .env. Change .env and run it again instead of editing this file.
on_http_request:
  # GitHub's webhook cannot sign in. It is protected by the HMAC signature and only POST /webhook is forwarded by the gateway.
  # Every other request must sign in first ...
  - expressions:
      - "req.url.path != '/webhook'"
    actions:
      - type: oauth
        config:
          provider: {provider}
  # ... and only these accounts get through.
  - expressions:
      - "req.url.path != '/webhook'"
      - "!(actions.ngrok.oauth.identity.email in [{listed}])"
    actions:
      - type: deny
        config:
          status_code: 403
"""


def build_command(port: int, url: str, policy_file: str | None) -> list[str]:
    cmd = ["ngrok", "http", str(int(port))]
    if url:
        cmd += ["--url", url]
    if policy_file:
        cmd += ["--traffic-policy-file", policy_file]
    return cmd


@dataclass
class TunnelPlan:
    command: list[str]
    policy: str | None        # None = no ngrok sign-in (--no-signin)
    emails: list[str]
    url: str                  # "" = ngrok picks the address


def plan_from_env(env: Mapping[str, str], gateway_port: int, policy_file: str, no_signin: bool = False) -> TunnelPlan:
    """Everything start_tunnel.py and start_all.py --tunnel need, from the environment (.env).
    Raises ValueError with a message meant for the person running it."""
    url = parse_url(env.get("NGROK_URL", ""))
    provider = (env.get("NGROK_OAUTH_PROVIDER", "google") or "google").strip().lower()
    emails = parse_emails(env.get("NGROK_ALLOWED_EMAILS", ""))
    policy = None
    if not no_signin:
        if not emails:
            raise ValueError("NGROK_ALLOWED_EMAILS is empty. Put the e-mail addresses that may open the dashboard in .env "
                             "(or pass --no-signin to rely on the dashboard log-in alone).")
        policy = build_policy(emails, provider)
    return TunnelPlan(build_command(gateway_port, url, policy_file if policy else None), policy, emails, url)
